// A placeholder low-poly car (until there's a modelled one):
//   resources/meshes/car.usda
// Meshes: "body", and the wheels "wheel_fl", "wheel_fr", "wheel_rl",
// "wheel_rr" (front/rear, left/right), which the game moves on their own
// (src/Car.js: the body sways on its suspension, the wheels stay on the road).
// Model space: +z forward, y up, +x the car's left. The body's origin is on
// the ground between the axles; a wheel's origin is its centre. Car.js has
// the wheels' places (WHEEL_X, WHEEL_Z, WHEEL_RADIUS below).
// Usage: node apps/marginal/tools/build_car.mjs
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Mesh, triangulate, write_usda } from "./geometry.mjs";
import { palette_uv } from "./textures.mjs";

const APP = join(dirname(fileURLToPath(import.meta.url)), "..");

// Extrudes a side profile ([z, y] points, convex) across x = -hw..hw.
function extrude(mesh, profile, hw, color, cap_color = color) {
  const uv = palette_uv(color), cap = palette_uv(cap_color);
  const cz = profile.reduce((s, p) => s + p[0], 0) / profile.length;
  const cy = profile.reduce((s, p) => s + p[1], 0) / profile.length;
  for (const side of [1, -1]) {
    // triangulate works on [x, z]-like pairs: use (z, y).
    for (const [a, b, c] of triangulate(profile)) {
      const P = (i) => [side * hw, profile[i][1], profile[i][0]];
      mesh.tri(P(a), P(b), P(c), uv, [side, 0, 0]);
    }
  }
  for (let i = 0; i < profile.length; i++) {
    const [z0, y0] = profile[i], [z1, y1] = profile[(i + 1) % profile.length];
    const out = [0, (y0 + y1) / 2 - cy, (z0 + z1) / 2 - cz];
    mesh.quad([-hw, y0, z0], [hw, y0, z0], [hw, y1, z1], [-hw, y1, z1], cap, out);
  }
}
// Axis-aligned box.
function box(mesh, [x0, y0, z0], [x1, y1, z1], color) {
  const uv = palette_uv(color);
  const c = [(x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2];
  const faces = [
    [[x1, y0, z0], [x1, y1, z0], [x1, y1, z1], [x1, y0, z1]],
    [[x0, y0, z0], [x0, y1, z0], [x0, y1, z1], [x0, y0, z1]],
    [[x0, y1, z0], [x1, y1, z0], [x1, y1, z1], [x0, y1, z1]],
    [[x0, y0, z0], [x1, y0, z0], [x1, y0, z1], [x0, y0, z1]],
    [[x0, y0, z1], [x1, y0, z1], [x1, y1, z1], [x0, y1, z1]],
    [[x0, y0, z0], [x1, y0, z0], [x1, y1, z0], [x0, y1, z0]],
  ];
  for (const f of faces) {
    const m = f.reduce((s, p) => [s[0] + p[0] / 4, s[1] + p[1] / 4, s[2] + p[2] / 4], [0, 0, 0]);
    mesh.quad(...f, uv, [m[0] - c[0], m[1] - c[1], m[2] - c[2]]);
  }
}
const WHEEL_X = 0.8, WHEEL_Z = 1.31, WHEEL_RADIUS = 0.34, WHEEL_WIDTH = 0.24;
// Wheel: an octagonal prism around the x axis, centred on the origin. The
// hub caps (both sides) are in two colors, so the wheel is seen to turn.
function wheel(name) {
  const mesh = new Mesh(name, "palette");
  const corner = (i, r) => {
    const a = ((i + 0.5) / 8) * Math.PI * 2;
    return [Math.cos(a) * r, Math.sin(a) * r]; // [z, y]
  };
  extrude(mesh, [...Array(8).keys()].map((i) => corner(i, WHEEL_RADIUS)), WHEEL_WIDTH / 2, "car_tyre");
  for (const side of [1, -1]) {
    const x = side * (WHEEL_WIDTH / 2 + 0.005);
    for (let i = 0; i < 8; i++) {
      const [z0, y0] = corner(i, 0.21), [z1, y1] = corner(i + 1, 0.21);
      mesh.tri([x, 0, 0], [x, y0, z0], [x, y1, z1], palette_uv(i % 4 < 2 ? "car_hub" : "car_trim"), [side, 0, 0]);
    }
  }
  return mesh;
}

const car = new Mesh("body", "palette");
// Body: side profile from the rear bumper to the nose.
extrude(car, [
  [-2.12, 0.32], [2.02, 0.32], [2.14, 0.52], [2.04, 0.74], [0.95, 0.86], [-1.85, 0.92], [-2.14, 0.76],
], 0.88, "car_body");
// Cabin (glass) and roof.
extrude(car, [[-1.55, 0.9], [0.9, 0.87], [0.12, 1.33], [-1.3, 1.36]], 0.76, "car_glass");
box(car, [-0.7, 1.33, -1.28], [0.7, 1.39, 0.1], "car_body");
// Lights.
box(car, [-0.78, 0.55, 2.06], [-0.42, 0.66, 2.1], "car_light");
box(car, [0.42, 0.55, 2.06], [0.78, 0.66, 2.1], "car_light");
box(car, [-0.8, 0.62, -2.17], [-0.45, 0.72, -2.1], "car_tail");
box(car, [0.45, 0.62, -2.17], [0.8, 0.72, -2.1], "car_tail");
// Bumpers.
box(car, [-0.9, 0.3, 2.0], [0.9, 0.42, 2.16], "car_trim");
box(car, [-0.9, 0.3, -2.18], [0.9, 0.44, -2.06], "car_trim");
// The wheels are all the same mesh; the body hides their inner half.
const wheels = ["wheel_fl", "wheel_fr", "wheel_rl", "wheel_rr"].map(wheel);

mkdirSync(join(APP, "resources/meshes"), { recursive: true });
writeFileSync(
  join(APP, "resources/meshes/car.usda"),
  write_usda([car, ...wheels], { palette: "../images/palette.png" }, "Placeholder car for Marginal. Generated by apps/marginal/tools/build_car.mjs.")
);
console.log(`car: body ${car.triangles} triangles, wheels 4 x ${wheels[0].triangles}`);
console.log(`wheels at x = +-${WHEEL_X}, z = +-${WHEEL_Z}, radius ${WHEEL_RADIUS}`);
